import express from "express";
import cors from "cors";
import helmet from "helmet";
import crypto from "node:crypto";
import apiRouter from "./routes/api.js";
import authRouter from "./routes/auth.js";
import accountsRouter from "./routes/accounts.js";
import { isSupabaseConfigured, supabase } from "./config/supabase.js";
import { rateLimit } from "./middleware/request.js";
import { requestLogger } from "./middleware/logging.js";
import { notFound, errorHandler } from "./middleware/errors.js";

const app = express();
const env = process.env.NODE_ENV || "development";
const origins = (process.env.CLIENT_URL || "http://localhost:5173").split(",").map((x) => x.trim()).filter(Boolean);
if (process.env.TRUST_PROXY === "true") app.set("trust proxy", 1);
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({ origin: (origin, cb) => !origin || origins.includes(origin) ? cb(null, true) : cb(new Error("Origin not allowed by CORS")), credentials: true, methods: ["GET", "POST", "PATCH", "DELETE", "OPTIONS"], allowedHeaders: ["Content-Type", "Authorization"] }));
app.use(express.json({ limit: "1mb" }));
app.use((req, res, next) => { req.id = req.get("x-request-id") || crypto.randomUUID(); res.setHeader("x-request-id", req.id); next(); });
app.use(requestLogger);
app.use(rateLimit({ max: Number(process.env.RATE_LIMIT_MAX) || 120 }));
app.get("/", (req, res) => res.json({ name: "NIVASA Smart Hostel Management API", status: "active", version: "1.0.0", endpoints: { health: "/api/health", auth: "/api/auth/me", dashboard: "/api/dashboard" } }));
app.get("/api/health/live", (req, res) => res.json({ status: "ok", service: "nivasa-api", timestamp: new Date().toISOString() }));
app.get("/api/health/ready", (req, res) => res.status(isSupabaseConfigured() ? 200 : 503).json({ status: isSupabaseConfigured() ? "ready" : "not_ready", checks: { supabaseConfiguration: isSupabaseConfigured() ? "configured" : "missing" }, timestamp: new Date().toISOString() }));
app.get("/api/health", async (req, res) => { let database = "unconfigured"; if (supabase) { const { error } = await supabase.from("students").select("id").limit(1); database = error ? "error" : "connected"; } res.status(database === "error" ? 503 : 200).json({ status: database === "error" ? "degraded" : "ok", database, timestamp: new Date().toISOString() }); });
app.use("/api/auth", authRouter);
app.use("/api/accounts", accountsRouter);
app.use("/api", apiRouter);
app.use(notFound);
app.use(errorHandler);
export default app;
